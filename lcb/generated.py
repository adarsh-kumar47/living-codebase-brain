"""Which application source files are generated code.

Generated code -- MyBatis models and mappers, OpenAPI clients, jOOQ tables -- is real
code the application calls, so it stays in the graph. But nobody edits it by hand, so
its git history is noise: on macrozheng/mall, 20,762 of 22,502 application methods
were MyBatis Generator output, and tracing their history was most of the ingest time
while diluting every fix commit that regenerated them. Generated files are marked
`is_generated` and get no history.

Bytecode cannot tell: `@Generated` has source retention. So it is read from the
repository, three ways:

1. **Generator configs** name the packages they write: MyBatis Generator
   (`targetPackage`), OpenAPI/Swagger codegen (`modelPackage`, `apiPackage`,
   `invokerPackage`), jOOQ (`<target><packageName>`). This is what catches mall,
   whose generated files carry no marker at all.
2. **Markers** in the file: a `@Generated` annotation or MyBatis's `@mbg.generated`
   anywhere; "DO NOT EDIT", "auto-generated", "This file was generated", "Code
   generated by" in the header before the type declaration -- not further down, where
   "the id is auto-generated" is about data, not the file.
3. **Paths** with a `generated` / `generated-sources` / `generated-src` folder.
"""

import os
import re
import subprocess

CONFIG_PACKAGE_RES = [
    # MyBatis Generator: <javaModelGenerator targetPackage="com.acme.model" ...>
    re.compile(r'<(?:javaModelGenerator|javaClientGenerator|sqlMapGenerator)\b[^>]*?\btargetPackage="([\w.]+)"'),
    # OpenAPI / Swagger codegen, Maven configuration ...
    re.compile(r"<(?:modelPackage|apiPackage|invokerPackage)>\s*([\w.]+)\s*</"),
    # ... and Gradle (modelPackage = "x", modelPackage.set("x"))
    re.compile(r"""\b(?:modelPackage|apiPackage|invokerPackage)\s*(?:=|\.set\()\s*["']([\w.]+)["']"""),
    # jOOQ: <target><packageName>com.acme.db</packageName>
    re.compile(r"<target>\s*<packageName>\s*([\w.]+)\s*</packageName>"),
]
CONFIG_GLOBS = ("*.xml", "*.gradle", "*.gradle.kts")

# Anywhere in the file. `\b(?!Value)` keeps JPA's @GeneratedValue out.
ANYWHERE_RE = re.compile(
    r"@(?:javax\.annotation\.(?:processing\.)?|jakarta\.annotation\.(?:processing\.)?)?Generated\b(?!Value)"
    r"|@mbg\.generated")
# Only in the header, before the first type declaration.
HEADER_RE = re.compile(
    r"DO NOT EDIT|auto-?generated|autogenerated|This (?:file|class|code) (?:was|is) "
    r"(?:automatically )?generated|Code generated by|Generated by the protocol buffer compiler",
    re.IGNORECASE)
TYPE_DECL_RE = re.compile(r"^\s*(?:(?:public|protected|private|abstract|final|sealed|static)\s+)*"
                          r"(?:class|interface|enum|record|@interface|object)\b", re.M)
GENERATED_DIRS = {"generated", "generated-sources", "generated-src"}
MAX_CONFIG_BYTES = 2_000_000


def tracked(repo, *patterns):
    out = subprocess.run(["git", "-C", repo, "ls-files", "-z", "--", *patterns],
                         capture_output=True, text=True, check=True).stdout
    return [p for p in out.split("\0") if p]


def generator_packages(repo):
    """{package: config file} for every package a generator config says it writes."""
    found = {}
    for rel in tracked(repo, *CONFIG_GLOBS):
        path = os.path.join(repo, rel)
        try:
            if os.path.getsize(path) > MAX_CONFIG_BYTES:
                continue
            with open(path, encoding="utf-8", errors="ignore") as fh:
                text = fh.read()
        except OSError:
            continue
        for regex in CONFIG_PACKAGE_RES:
            for pkg in regex.findall(text):
                found.setdefault(pkg, rel)
    return found


def marker_reason(text):
    if ANYWHERE_RE.search(text):
        return "marked @Generated"
    decl = TYPE_DECL_RE.search(text)
    header = text[: decl.start()] if decl else text[:4000]
    m = HEADER_RE.search(header)
    return f'header says "{m.group(0)}"' if m else None


def find_generated(repo, files):
    """files: {repo-relative source path: Java package}. Returns {path: reason} for the
    ones that are generated."""
    packages = generator_packages(repo)
    result = {}
    for path, package in files.items():
        parts = path.replace(os.sep, "/").split("/")
        if GENERATED_DIRS & set(parts[:-1]):
            result[path] = "in a generated-sources folder"
            continue
        owner = next((p for p in packages if package == p or (package or "").startswith(p + ".")), None)
        if owner:
            result[path] = f"package {owner} is written by the generator config {packages[owner]}"
            continue
        try:
            with open(os.path.join(repo, path), encoding="utf-8", errors="ignore") as fh:
                reason = marker_reason(fh.read())
        except OSError:
            continue
        if reason:
            result[path] = reason
    return result
